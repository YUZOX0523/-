// デジライズ社員が生成済み原稿に修正指示を出したときのプロンプト。
// SYSTEM_PROMPT の絶対ルールは修正時も適用され続ける。
export function buildReviseInstruction(
  format: "draft" | "wordpress",
  currentText: string,
  instruction: string
): string {
  const formatNote =
    format === "draft"
      ? "出力形式は元の原稿と同じMarkdown(YAML frontmatter含む)を維持してください。"
      : "出力形式は元の原稿と同じGutenbergブロックマークアップ(冒頭のHTMLコメント込み)を維持してください。";

  return `以下は既存の導入事例原稿です。

---
${currentText}
---

上記の原稿に対して、次の修正指示に従って全文を書き直してください。

【修正指示】
${instruction}

【厳守事項】
- ${formatNote}
- 数値・固有名詞は元の原稿、および添付されていればPDFに記載されている範囲のみを使う。指示に無い新しい数値を創作しない。
- 受講者の個人名は載せない。声は匿名のまま維持する。
- 画像挿入位置マーカー(【画像挿入位置①/②】)は指示が無い限りそのまま残す。
- 出力は修正後の原稿全文のみ。前置き・説明・変更点の要約・確認の質問などは一切書かない。`;
}
